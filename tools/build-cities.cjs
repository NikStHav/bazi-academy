// Generates www/js/cities-data.js from GeoNames data (via the all-the-cities npm package, CC BY 4.0)
// and IANA time zones from coordinates (tz-lookup, CC0). Neither package ships with the app.
// Usage: node tools/build-cities.cjs <folder containing node_modules/all-the-cities and tz-lookup>
const fs = require('fs');
const path = require('path');
const dir = process.argv[2];
const cities = require(path.join(dir, 'node_modules/all-the-cities'));
const tzlookup = require(path.join(dir, 'node_modules/tz-lookup'));
const DACH = new Set(['DE', 'AT', 'CH', 'LI', 'LU']);
const keep = cities.filter((c) => c.featureCode !== 'PPLX' && !/\(Kreis/.test(c.name)).filter((c) => c.population >= 15000 || (DACH.has(c.country) && c.population >= 5000));
const tzs = [];
const tzIndex = new Map();
const rows = [];
for (const c of keep.sort((a, b) => b.population - a.population)) {
  const [lon, lat] = c.loc.coordinates;
  const tz = tzlookup(lat, lon);
  if (!tzIndex.has(tz)) { tzIndex.set(tz, tzs.length); tzs.push(tz); }
  const name = c.name.replace(/[|\n]/g, ' ');
  rows.push([name, c.country, lat.toFixed(2), lon.toFixed(2), tzIndex.get(tz), Math.max(1, Math.round(c.population / 1000))].join('|'));
}
const out = `// Generated by tools/build-cities.cjs – do not edit.
// City data © GeoNames (geonames.org), CC BY 4.0. Time zones via tz-lookup (CC0).
// Row format: name|country|lat|lon|timeZoneIndex|populationInThousands, sorted by population.
export const TZ = ${JSON.stringify(tzs)};
export const DATA = ${JSON.stringify(rows.join('\n'))};
`;
fs.writeFileSync(path.join(__dirname, '..', 'www/js/cities-data.js'), out);
console.log(rows.length, 'cities,', tzs.length, 'time zones,', (out.length / 1024).toFixed(0), 'KB');
console.log('check:', ['Bad Homburg vor der Höhe', 'Aachen', 'Sydney', 'Shanghai', 'New York City'].map((n) => rows.find((r) => r.startsWith(n + '|'))).join('\n       '));
