// Builds the website: the support/legal pages from docs/ at the root and the web app under app/.
//   node tools/build-web.cjs [outDir=dist/site] [build label]
// The web app is the same code as the phone app with WEB_BUILD = true: Premium features point to the
// stores, there are no notifications, and a service worker makes it work offline and installable.
const fs = require('fs');
const path = require('path');
const crypto = require('crypto');

const root = path.join(__dirname, '..');
const out = path.resolve(root, process.argv[2] || 'dist/site');
const label = process.argv[3] || 'local';
const app = path.join(out, 'app');

fs.rmSync(out, { recursive: true, force: true });
fs.cpSync(path.join(root, 'docs'), out, { recursive: true });
fs.cpSync(path.join(root, 'www'), app, { recursive: true });

const flags = path.join(app, 'js/build-flags.js');
let f = fs.readFileSync(flags, 'utf8');
if (!f.includes('export const WEB_BUILD = false;')) throw new Error('WEB_BUILD flag not found');
f = f.replace('export const WEB_BUILD = false;', 'export const WEB_BUILD = true;').replace("export const BUILD = 'local';", `export const BUILD = 'web-${label}';`);
fs.writeFileSync(flags, f);

const index = path.join(app, 'index.html');
let html = fs.readFileSync(index, 'utf8');
html = html.replace('<title>BaZi Academy</title>', `<title>BaZi Academy – Four Pillars calculator & lessons · Vier Säulen lernen</title>
  <meta name="description" content="Learn Chinese astrology (BaZi, Four Pillars of Destiny): free chart calculator with solar terms and true solar time, daily card, lessons and lunar calendar. Chinesische Astrologie lernen: BaZi-Rechner, Tageskarte, Lektionen und Mondkalender.">`);
fs.writeFileSync(index, html);

// Service worker: precache every file of the app; a new build gets a new cache name.
const files = [];
(function walk(dir) {
  for (const e of fs.readdirSync(dir, { withFileTypes: true })) {
    const p = path.join(dir, e.name);
    if (e.isDirectory()) walk(p); else files.push(path.relative(app, p).split(path.sep).join('/'));
  }
})(app);
const hash = crypto.createHash('sha256');
files.sort().forEach((x) => hash.update(x).update(fs.readFileSync(path.join(app, x))));
const version = hash.digest('hex').slice(0, 12);
fs.writeFileSync(path.join(app, 'sw.js'), `// Generated by tools/build-web.cjs – offline cache for the BaZi Academy web app.
const CACHE = 'bazi-${version}';
const FILES = ${JSON.stringify(['./', ...files])};
self.addEventListener('install', (e) => { e.waitUntil(caches.open(CACHE).then((c) => c.addAll(FILES)).then(() => self.skipWaiting())); });
self.addEventListener('activate', (e) => {
  e.waitUntil(caches.keys().then((ks) => Promise.all(ks.filter((k) => k !== CACHE).map((k) => caches.delete(k)))).then(() => self.clients.claim()));
});
self.addEventListener('fetch', (e) => {
  const r = e.request;
  if (r.method !== 'GET' || new URL(r.url).origin !== location.origin) return;
  e.respondWith(caches.match(r, { ignoreSearch: true }).then((hit) => hit || fetch(r).catch(() => (r.mode === 'navigate' ? caches.match('index.html') : Response.error()))));
});
`);
console.log(`Website built in ${path.relative(root, out)} (${files.length} app files, cache ${version})`);
